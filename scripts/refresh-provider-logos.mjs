// Regenerates src/utils/providerLogos.js from TMDB's provider list.
//
// TMDB's API terms cap caching their content at six months, so the generated
// file carries the date it was made and this has to be re-run before that
// lapses. One command rather than a research task is the point.
//
//   node scripts/refresh-provider-logos.mjs
//
// Needs TMDB_READ_ACCESS_TOKEN, which it reads from the environment or .env.
import { readFileSync, writeFileSync } from "node:fs";
import { AVAILABLE_STREAMING_SERVICES, normalizeServiceName } from "../src/utils/streamingServices.js";

const OUTPUT = new URL("../src/utils/providerLogos.js", import.meta.url);

function readToken() {
  if (process.env.TMDB_READ_ACCESS_TOKEN) return process.env.TMDB_READ_ACCESS_TOKEN;
  try {
    const env = readFileSync(new URL("../.env", import.meta.url), "utf8");
    return env.match(/^TMDB_READ_ACCESS_TOKEN=(.+)$/m)?.[1]?.trim() || "";
  } catch {
    return "";
  }
}

const token = readToken();
if (!token) {
  console.error("[refresh-provider-logos] TMDB_READ_ACCESS_TOKEN is not set");
  process.exit(2);
}

const response = await fetch(
  "https://api.themoviedb.org/3/watch/providers/movie?watch_region=US",
  { headers: { Authorization: `Bearer ${token}`, Accept: "application/json" } }
);
if (!response.ok) {
  console.error(`[refresh-provider-logos] TMDB responded ${response.status}`);
  process.exit(1);
}

const { results = [] } = await response.json();
const supported = new Set(AVAILABLE_STREAMING_SERVICES);
const logos = {};

// TMDB lists a service under several entries (channel add-ons, live variants).
// display_priority orders them the way TMDB itself would, so the lowest wins
// and the account's own name for the service is the key.
[...results]
  .sort((a, b) => (a.display_priority ?? 1e6) - (b.display_priority ?? 1e6))
  .forEach((provider) => {
    const name = normalizeServiceName(provider.provider_name || "");
    if (supported.has(name) && provider.logo_path && !logos[name]) {
      logos[name] = provider.logo_path;
    }
  });

const missing = AVAILABLE_STREAMING_SERVICES.filter((name) => !logos[name]);
const entries = AVAILABLE_STREAMING_SERVICES.filter((name) => logos[name])
  .map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(logos[name])},`)
  .join("\n");

writeFileSync(
  OUTPUT,
  `// Generated by scripts/refresh-provider-logos.mjs on ${new Date().toISOString().slice(0, 10)}.
// Do not edit by hand.
//
// TMDB's API terms cap caching their content at six months, so re-run the
// script before this date is that old. A service missing from the map renders
// as its name, which is what every one of them did before logos existed.
const PROVIDER_LOGO_PATHS = {
${entries}
};

export function getServiceLogoPath(serviceName) {
  return PROVIDER_LOGO_PATHS[serviceName] || null;
}
`,
  "utf8"
);

console.log(
  `[refresh-provider-logos] wrote ${Object.keys(logos).length} logos` +
    (missing.length > 0 ? `; no TMDB match for: ${missing.join(", ")}` : "")
);
